"""The input deck as data: flat parameters plus repeatable groups.

WarpX input files are flat ``key = value`` lines, but several families of keys are
per-instance: every particle species owns ``<species>.charge``, every collision owns
``<collision>.collision_type``, and so on.  The catalog represents those families with
the placeholders the documentation uses (``<species_name>``, ``<collision_name>``,
``<diag_name>``, ``<reduced_diags_name>``, ``<laser_name>``, ``<solver_name>``), and this
module keeps them as groups so the UI can add or remove an instance with one click.

The list keys WarpX needs (``particles.species_names`` and friends) are derived from the
groups, so the user never has to keep two places in sync.
"""
from __future__ import annotations

import re
from collections import OrderedDict

TEMPLATE = re.compile(r"^(<[a-z_]+>)\.(.+)$")

# group placeholder -> the list key WarpX expects for that family
LIST_KEYS = {
    "<species_name>": "particles.species_names",
    "<collision_name>": "collisions.collision_names",
    "<diag_name>": "diagnostics.diags_names",
    "<reduced_diags_name>": "diagnostics.reduced_diags_names",
    "<laser_name>": "lasers.names",
    "<solver_name>": None,
}


class Deck:
    """A WarpX input deck: ``params`` (flat) + ``groups`` (one dict per instance)."""

    def __init__(self) -> None:
        self.params: "OrderedDict[str, str]" = OrderedDict()
        self.groups: "OrderedDict[str, OrderedDict[str, OrderedDict[str, str]]]" = OrderedDict()

    # -- editing -----------------------------------------------------------
    def set(self, name: str, value) -> None:
        if value is None or str(value).strip() == "":
            self.params.pop(name, None)
        else:
            self.params[name] = str(value).strip()

    def get(self, name: str, default=None):
        return self.params.get(name, default)

    def add_instance(self, template: str, instance: str) -> None:
        self.groups.setdefault(template, OrderedDict()).setdefault(instance, OrderedDict())

    def remove_instance(self, template: str, instance: str) -> None:
        self.groups.get(template, {}).pop(instance, None)

    def set_group_value(self, template: str, instance: str, key: str, value) -> None:
        bucket = self.groups.setdefault(template, OrderedDict()).setdefault(instance, OrderedDict())
        if value is None or str(value).strip() == "":
            bucket.pop(key, None)
        else:
            bucket[key] = str(value).strip()

    def instances(self, template: str) -> list[str]:
        return list(self.groups.get(template, {}))

    # -- serialisation -----------------------------------------------------
    def sync_lists(self) -> None:
        """Write the ``*_names`` list keys from the instances that exist."""
        for template, list_key in LIST_KEYS.items():
            if not list_key:
                continue
            names = self.instances(template)
            if names:
                self.params[list_key] = " ".join(names)
            else:
                self.params.pop(list_key, None)

    def to_inputs(self) -> str:
        self.sync_lists()
        lines = ["# Generated by WarpX Studio", ""]
        for key, value in self.params.items():
            lines.append(f"{key} = {value}")
        for template, instances in self.groups.items():
            if not instances:
                continue
            lines.append("")
            lines.append(f"# ---- {template.strip('<>')} ----")
            for instance, values in instances.items():
                for key, value in values.items():
                    lines.append(f"{instance}.{key} = {value}")
        return "\n".join(lines) + "\n"

    @classmethod
    def from_inputs(cls, text: str) -> "Deck":
        deck = cls()
        raw: list[tuple[str, str]] = []
        for line in text.splitlines():
            stripped = line.split("#", 1)[0].strip()
            if not stripped or "=" not in stripped:
                continue
            key, value = stripped.split("=", 1)
            raw.append((key.strip(), value.strip()))
        # first pass: which instances exist, from the list keys
        instances: dict[str, set[str]] = {}
        for key, value in raw:
            for template, list_key in LIST_KEYS.items():
                if list_key == key:
                    instances.setdefault(template, set()).update(value.split())
        # second pass: route each key to its group or to the flat table
        for key, value in raw:
            head, _, rest = key.partition(".")
            if rest and head in instances.get(_template_of(head, instances), set()):
                deck.set_group_value(_template_of(head, instances), head, rest, value)
            else:
                deck.set(key, value)
        return deck

    def as_dict(self) -> dict:
        return {"params": dict(self.params),
                "groups": {t: {i: dict(v) for i, v in inst.items()}
                           for t, inst in self.groups.items()}}


def _template_of(head: str, instances: dict[str, set[str]]) -> str:
    for template, names in instances.items():
        if head in names:
            return template
    return "<dynamic>"


DIM_DEFAULTS = {
    # dims: (geometry.dims, n_cell, prob_lo, prob_hi, ppc, species ranges)
    "1d": ("1", "64", "0.0", "40.e-6", "1", {"zmin": "0.0", "zmax": "40.e-6"}),
    "2d": ("2", "64 64", "-20.e-6 -20.e-6", "20.e-6 20.e-6", "1 1",
           {"xmin": "-20.e-6", "xmax": "20.e-6", "zmin": "-20.e-6", "zmax": "20.e-6"}),
    "3d": ("3", "32 32 32", "-10.e-6 -10.e-6 -10.e-6", "10.e-6 10.e-6 10.e-6",
           "1 1 1", {"xmin": "-10.e-6", "xmax": "10.e-6", "ymin": "-10.e-6",
                     "ymax": "10.e-6", "zmin": "-10.e-6", "zmax": "10.e-6"}),
    "rz": ("RZ", "64 64", "0.0 -20.e-6", "20.e-6 20.e-6", "1 1",
           {"xmin": "0.0", "xmax": "20.e-6", "zmin": "-20.e-6", "zmax": "20.e-6"}),
}


def minimal_deck(dims: str = "2d") -> Deck:
    """The smallest deck for one dimensionality that actually runs.

    Derived from ``Examples/Tests/langmuir/inputs_base_2d`` (a deck this fork's own test
    suite runs) with a coarse grid.  ``algo.particle_shape``, ``<species>.profile`` and
    ``<species>.momentum_distribution_type`` are mandatory reads in this fork (``get``
    rather than ``query``), which is why they are present even for a cold plasma.

    Everything dimensionality dependent - the number of ``amr.n_cell`` entries, the
    range keys of a species, the per-direction particle count - comes from
    ``DIM_DEFAULTS`` so the wizard cannot produce a 2D deck for a 1D binary.
    """
    if dims not in DIM_DEFAULTS:
        raise ValueError(f"unknown dims {dims!r}; expected one of {sorted(DIM_DEFAULTS)}")
    geom_dims, n_cell, lo, hi, ppc, ranges = DIM_DEFAULTS[dims]

    deck = Deck()
    deck.set("max_step", "40")
    deck.set("amr.n_cell", n_cell)
    deck.set("amr.max_grid_size", "32")
    deck.set("amr.max_level", "0")
    deck.set("geometry.dims", geom_dims)
    deck.set("geometry.prob_lo", lo)
    deck.set("geometry.prob_hi", hi)
    deck.set("boundary.field_lo", " ".join(["periodic"] * len(n_cell.split())))
    deck.set("boundary.field_hi", " ".join(["periodic"] * len(n_cell.split())))
    deck.set("boundary.particle_lo", " ".join(["periodic"] * len(n_cell.split())))
    deck.set("boundary.particle_hi", " ".join(["periodic"] * len(n_cell.split())))
    deck.set("warpx.cfl", "0.99")
    deck.set("warpx.verbose", "1")
    deck.set("algo.maxwell_solver", "yee")
    deck.set("algo.particle_shape", "1")
    if geom_dims == "RZ":
        deck.set("warpx.n_rz_azimuthal_modes", "2")

    deck.add_instance("<species_name>", "electrons")
    for key, value in (
        ("charge", "-q_e"),
        ("mass", "m_e"),
        ("injection_style", "NUniformPerCell"),
        ("num_particles_per_cell_each_dim", ppc),
        ("profile", "constant"),
        ("density", "1.e24"),
        ("momentum_distribution_type", "constant"),
    ):
        deck.set_group_value("<species_name>", "electrons", key, value)
    for key, value in ranges.items():
        deck.set_group_value("<species_name>", "electrons", key, value)

    deck.add_instance("<diag_name>", "chk")
    for key, value in (
        ("diag_type", "Full"),
        ("format", "checkpoint"),
        ("intervals", "20"),
        ("write_species", "1"),
        ("file_prefix", "chk"),
    ):
        deck.set_group_value("<diag_name>", "chk", key, value)

    deck.add_instance("<diag_name>", "diag1")
    for key, value in (
        ("diag_type", "Full"),
        ("format", "openpmd"),
        ("fields_to_plot", "Ex Ey Ez Bx By Bz rho"),
        ("intervals", "10"),
        ("write_species", "1"),
        ("file_prefix", "diag1"),
    ):
        deck.set_group_value("<diag_name>", "diag1", key, value)
    return deck


def minimal_2d_deck() -> Deck:
    """Backwards compatible helper used by older callers."""
    return minimal_deck("2d")
